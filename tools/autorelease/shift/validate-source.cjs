'use strict';
const fs = require('node:fs');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const [sourcePath] = process.argv.slice(2);
assert.ok(sourcePath, 'Usage: node validate-source.cjs SOURCE_HTML');
const bytes = fs.readFileSync(sourcePath);
const source = bytes.toString('utf8');
assert.equal(Buffer.compare(Buffer.from(source), bytes), 0, 'Source must be exact UTF-8 bytes');
const pattern = /https:\/\/cdnjs\.cloudflare\.com\/ajax\/libs\/pdf\.js\/(4\.\d+\.\d+)\/(pdf(?:\.worker)?\.min\.mjs)/g;
const found = [...source.matchAll(pattern)];
assert.equal(found.length, 2, 'Exactly two existing PDF.js 4 version URLs');
assert.equal(found[0][1], found[1][1], 'Main and worker must use one version');
const version = found[0][1];
const [major, minor, patch] = version.split('.').map(Number);
assert.ok([major, minor, patch].every(Number.isSafeInteger) && `${major}.${minor}.${patch}` === version, 'Canonical stable numeric version required');
assert.ok(major === 4 && (minor > 10 || (minor === 10 && patch >= 38)), 'No major change or downgrade below verified 4.10.38');
const normalized = source.replace(pattern, (_, ignored, name) => `https://cdnjs.cloudflare.com/ajax/libs/pdf.js/__PDFJS_VERSION__/${name}`);
assert.equal(crypto.createHash('sha256').update(normalized).digest('hex'), '90cfdcbc0eceef76603c71aeef3b98f38740b643dcdcd803b916286b9db9aa7d', 'Only the two version tokens may change from the approved runtime');
